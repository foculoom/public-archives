#!/usr/bin/env python3
"""Report files that are large enough to affect AI operability.

De-branded standalone version. No dependency on .factory/ paths.
Configuration via ./size-thresholds.json in repo root, or defaults.
"""

from __future__ import annotations

import argparse
import json
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any


SOURCE_EXTENSIONS = {".py", ".swift", ".gd", ".ts", ".tsx", ".js", ".jsx"}
MARKDOWN_EXTENSIONS = {".md", ".mdx"}
CONFIG_FILE = Path("size-thresholds.json")
IGNORED_PARTS = {
    ".git",
    "build",
    "dist",
    "node_modules",
    "DerivedData",
    ".venv",
    "venv",
    ".build",
    "Pods",
    "Carthage",
    "__pycache__",
    ".pytest_cache",
    ".mypy_cache",
    ".ruff_cache",
}
GENERATED_MARKERS = (
    "@generated",
    "generated by",
    "this file was generated",
    "automatically generated",
    "do not edit",
    "code generated",
)
VENDOR_PARTS = {"vendor", "vendors", "third_party", "third-party", "external"}


@dataclass(frozen=True)
class Finding:
    path: Path
    lines: int
    classification: str
    category: str


def default_config() -> dict[str, Any]:
    return {
        "source": {
            "extensions": sorted(SOURCE_EXTENSIONS),
            "warn": 500,
            "smell": 800,
            "critical": 2000,
        },
        "markdown": {
            "extensions": sorted(MARKDOWN_EXTENSIONS),
            "warn": 500,
            "smell": 800,
            "critical": 2000,
        },
    }


def load_config(root: Path) -> dict[str, Any]:
    path = root / CONFIG_FILE
    if not path.exists():
        return default_config()
    try:
        loaded = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return default_config()
    if not isinstance(loaded, dict):
        return default_config()
    config = default_config()
    for key, value in loaded.items():
        if isinstance(value, dict) and isinstance(config.get(key), dict):
            config[key].update(value)
        else:
            config[key] = value
    return config


def classify(line_count: int, warn: int, smell: int, critical: int) -> str:
    if line_count >= critical:
        return "DEFECT"
    if line_count >= smell:
        return "SMELL"
    if line_count >= warn:
        return "WATCH"
    return "NORMAL"


def is_ignored_path(path: Path) -> bool:
    return bool(set(path.parts) & IGNORED_PARTS)


def is_vendor_path(path: Path) -> bool:
    return bool(set(part.lower() for part in path.parts) & VENDOR_PARTS)


def looks_generated(path: Path) -> bool:
    try:
        with path.open("r", encoding="utf-8", errors="ignore") as handle:
            sample = "\n".join(handle.readline() for _ in range(20)).lower()
    except OSError:
        return False
    return any(marker in sample for marker in GENERATED_MARKERS)


def line_count(path: Path) -> int:
    with path.open("r", encoding="utf-8", errors="ignore") as handle:
        return sum(1 for _ in handle)


def category_for(path: Path, config: dict[str, Any]) -> tuple[str, int, int, int] | None:
    suffix = path.suffix.lower()
    for category in ("source", "markdown"):
        settings = config.get(category, {})
        extensions = settings.get("extensions", []) if isinstance(settings, dict) else []
        if suffix in extensions:
            return (
                category,
                int(settings.get("warn", 500)),
                int(settings.get("smell", 800)),
                int(settings.get("critical", 2000)),
            )
    return None


def scan(root: Path) -> list[Finding]:
    findings: list[Finding] = []
    config = load_config(root)
    for path in root.rglob("*"):
        if not path.is_file():
            continue
        relative = path.relative_to(root)
        if is_ignored_path(relative):
            continue
        category = category_for(relative, config)
        if category is None:
            continue
        category_name, warn, smell, critical = category
        if looks_generated(path) or is_vendor_path(relative):
            continue
        count = line_count(path)
        if count < warn:
            continue
        findings.append(
            Finding(
                path=relative,
                lines=count,
                classification=classify(count, warn, smell, critical),
                category=category_name,
            )
        )
    return sorted(findings, key=lambda item: (-item.lines, str(item.path)))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", default=".", help="Repository root to scan")
    args = parser.parse_args()

    root = Path(args.root).resolve()
    findings = scan(root)

    if findings:
        print("Files crossing configured size thresholds:")
        for finding in findings:
            print(f"{finding.lines:5} {finding.classification:8} {finding.category:8} {finding.path}")
    else:
        print("No files crossed configured size thresholds.")

    failing = [item for item in findings if item.classification == "DEFECT"]
    if failing:
        print(
            f"\n{len(failing)} file(s) over critical threshold. "
            "Split, reduce, or justify before proceeding."
        )
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
